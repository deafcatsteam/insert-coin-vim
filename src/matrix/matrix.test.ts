import { expect, test } from 'vitest';
import { replay } from '../engine/replay';
import { cases, type Case } from './cases';

const run = (c: Case): string => {
  const [line, ch] = c.cursor ?? [0, 0];
  try {
    return replay({ start: c.start, cursor: { line, ch } }, c.keys).buffer;
  } catch (error) {
    return `error: ${String(error)}`;
  }
};

/** Shows a value inside a Markdown table cell. */
const cell = (text: string): string =>
  `\`${JSON.stringify(text).slice(1, -1).replaceAll('|', '\\|')}\``;

// The committed file is the expectation: a row that changes status fails this test.
// Run "npm run matrix" to accept the new table.
test('support matrix matches docs/support-matrix.md', async () => {
  const rows = cases.map((c) => {
    const got = run(c);
    const status = got === c.want ? 'ok' : `FAIL, got ${cell(got)}`;
    return `| ${String(c.chapter)} | ${cell(c.command)} | ${cell(c.start)} | ${cell(c.keys)} | ${cell(c.want)} | ${status} |`;
  });
  const failed = rows.filter((row) => row.includes('| FAIL')).length;
  const doc = [
    '# Command support matrix',
    '',
    'Generated by `npm run matrix` from `src/matrix/cases.ts`. Do not edit by hand.',
    '',
    'Engine: `@replit/codemirror-vim`, replayed headless in jsdom.',
    'Expected buffers are hand-written from Vim documentation, not checked against a real Vim.',
    '',
    `Result: ${String(rows.length - failed)} of ${String(rows.length)} rows ok.`,
    '',
    '| Chapter | Command | Start buffer | Keys | Expected buffer | Status |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
  await expect(doc).toMatchFileSnapshot('../../docs/support-matrix.md');
});
